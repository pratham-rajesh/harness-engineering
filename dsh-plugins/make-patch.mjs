// make-patch.mjs -- writes dsh-plugins/cordis.local.yml: a DSH `--patch` overlay that loads the two plugins in this folder.
// DSH requires ABSOLUTE plugin paths in a patch, and an absolute path differs per machine, so the file is generated, not committed.
//
//   node dsh-plugins/make-patch.mjs
//   dsh --profile web --patch ./dsh-plugins/cordis.local.yml --no-open            # from a DSH checkout: pnpm dsh web --patch ...
//   dsh --profile web --patch ./dsh-plugins/cordis.local.yml --dump-config        # prints the composed config without booting
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const q = p => JSON.stringify(p.replaceAll('\\', '/'))          // JSON strings are valid YAML double-quoted scalars

const yaml = `# generated by make-patch.mjs -- do not commit (absolute paths)
- insert:
    - id: second-brain
      name: ${q(path.join(here, 'second-brain', 'src', 'index.js'))}
      config:
        root: ${q(path.join(here, '..', '.second-brain'))}
    - id: tool-ledger
      name: ${q(path.join(here, 'tool-ledger', 'src', 'index.js'))}
      config:
        defaultLimit: 50
        limits:
          bash: 10
          brain_save: 20
        logFile: ${q(path.join(here, '..', '.tool-ledger', 'audit.jsonl'))}
`
const out = path.join(here, 'cordis.local.yml')
writeFileSync(out, yaml, 'utf8')
console.log(`wrote ${out}`)
